def record(doc_id, source, sheet, kind, question, answer, attributes,
           status="ok", cells=None):
    rec = {"id": doc_id, "source": source, "sheet": sheet, "kind": kind,
           "question": question, "answer": answer, "images": [],
           "answer_is_image": False,
           "status": status,
           "review_reasons": ["unresolved_conflict"] if status == "needs_review" else [],
           "attributes": attributes, "image_capture_date": ""}
    if cells is not None:
        rec["cells"] = cells
    return rec


def build():
    docs = []
    counters = {}
    for entry in QA:
        sheet, question, answer, attributes = entry[:4]
        status = entry[4] if len(entry) > 4 else "ok"
        counters[sheet] = counters.get(sheet, 0) + 1
        n = counters[sheet]
        docs.append(record(f"faq:{sheet}:Q{n}", "faq", sheet, "qa", question, answer,
                           attributes, status))
    for title, text, attributes in SCRIPTS:
        docs.append(record(f"script:{title}", "script", "스크립트", "script", title, text,
                           attributes))
    cells = ["E2=NO", "F2=팀명", "H2=세부내용"]
    row = 3
    for no, team, topics in ROUTING:
        cells += [f"E{row}={no}", f"F{row}={team}", f"H{row}={topics[0]}"]
        row += 1
        for topic in topics[1:]:
            cells.append(f"H{row}={topic}")
            row += 1
    docs.append(record("manual:부서이관건", "manual", "부서이관건", "table", "",
                       f"{ORG} > 민원센터 > 부서이관건", {}, cells=cells))
    for title, text in PAGES:
        docs.append(record(f"manual:{title}", "manual", title, "page", "", text, {}))
    return docs


def main():
    docs = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(json.dumps(d, ensure_ascii=False) + "\n" for d in docs),
                   encoding="utf-8")
    print(f"{len(docs)} documents -> {OUT}")


if __name__ == "__main__":
    main()
